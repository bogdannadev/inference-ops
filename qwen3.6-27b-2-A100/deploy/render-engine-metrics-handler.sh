#!/usr/bin/env bash
# =============================================================================
# Render clickhouse/config.d/engine-metrics-handler.xml from
# clickhouse/engine-usage-metrics.sql, so the SQL stays readable and testable on
# its own (`curl --data-binary @clickhouse/engine-usage-metrics.sql`) and the
# XML is never hand-edited. Re-run after changing the .sql, then recreate the
# ClickHouse container: <http_handlers> is not hot-reloaded.
#
#   ./deploy/render-engine-metrics-handler.sh          # write
#   ./deploy/render-engine-metrics-handler.sh --check  # exit 1 if stale
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."
out=clickhouse/config.d/engine-metrics-handler.xml
tmp=$(mktemp)
{
  cat <<'XML'
<?xml version="1.0"?>
<!--
  GENERATED by deploy/render-engine-metrics-handler.sh from
  clickhouse/engine-usage-metrics.sql. Do not edit by hand.

  GET /engine_usage_metrics — exact per-consumer usage from engine.requests in
  Prometheus exposition format, scraped by Prometheus job `engine-usage` as
  the read-only user `engine_metrics` (users.d/engine-metrics.xml).

  <defaults/> keeps every stock handler (queries, /ping, /play); without it
  this file would replace them and Vector and admin-mcp would lose the database.
-->
<clickhouse>
  <http_handlers>
    <rule>
      <url>/engine_usage_metrics</url>
      <methods>GET</methods>
      <handler>
        <type>predefined_query_handler</type>
        <content_type>text/plain; version=0.0.4; charset=utf-8</content_type>
        <query><![CDATA[
XML
  grep -v '^--' clickhouse/engine-usage-metrics.sql
  cat <<'XML'
]]></query>
      </handler>
    </rule>
    <defaults/>
  </http_handlers>
</clickhouse>
XML
} > "$tmp"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$tmp" "$out" && { rm -f "$tmp"; echo "up to date"; } || { rm -f "$tmp"; echo "STALE: re-run $0" >&2; exit 1; }
else
  mv "$tmp" "$out"; chmod 644 "$out"; echo "wrote $out"
fi
